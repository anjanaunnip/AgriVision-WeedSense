# backend/reports/result_pdf.py

import os
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image
)
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from django.conf import settings

LOGO_PATH = os.path.join(settings.BASE_DIR, "backend/static/logo.png.jpeg")


def generate_result_pdf(data):
    """
    Generates the main result PDF.
    Returns PDF byte stream.
    """

    buffer = data["buffer"]
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=20, rightMargin=20, topMargin=20)

    styles = getSampleStyleSheet()
    elements = []

    # CORPORATE HEADER WITH LOGO
    header_cells = []

    if os.path.exists(LOGO_PATH):
        header_cells.append(Image(LOGO_PATH, width=60, height=60))
    else:
        header_cells.append(Paragraph("<b>AGRI VISION</b>", styles["Title"]))

    header_cells.append(Paragraph(
        "<b>AGRIVISION WEEDSENSE</b><br/><font size=10>AI Weed Detection & NDVI Analysis</font>",
        ParagraphStyle(name="HeaderStyle", alignment=1, textColor=colors.green)
    ))

    header_table = Table([header_cells], colWidths=[80, 400])
    header_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ALIGN", (1, 0), (1, 0), "CENTER"),
    ]))

    elements.append(header_table)
    elements.append(Spacer(1, 20))

    # TITLE
    elements.append(Paragraph(
        "<b><font size=18 color='#1b5e20'>Full Field Analysis Report</font></b>",
        ParagraphStyle(name="MainTitle", alignment=1)
    ))
    elements.append(Spacer(1, 10))

    # SUMMARY TABLE
    summary_data = [
        ["Crop Coverage", f"{data['crop']}%"],
        ["Weed Coverage", f"{data['weed']}%"],
        ["NDVI Score", data["ndvi"]],
        ["Field Health", data["health_status"]],
        ["Model Accuracy", f"{data['model_accuracy']}%"],
        ["Reliability Score", f"{data['reliability']}%"],
    ]

    summary_table = Table(summary_data, colWidths=[200, 200])
    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.lightgreen),
        ("BACKGROUND", (0, 1), (-1, -1), colors.whitesmoke),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.black),
        ("GRID", (0, 0), (-1, -1), 1, colors.gray),
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica-Bold"),
    ]))

    elements.append(summary_table)
    elements.append(Spacer(1, 20))

    # IMAGE IMPORT FUNCTION
    def add_image(title, path):
        elements.append(Paragraph(f"<b>{title}</b>", styles["Heading3"]))
        if os.path.exists(path):
            elements.append(Image(path, width=350, height=250))
        else:
            elements.append(Paragraph("<i>Image missing</i>", styles["Normal"]))
        elements.append(Spacer(1, 20))

    # ADD IMAGES
    add_image("NDVI Vegetation Map", data["ndvi_path"])
    add_image("Weed Detection Mask", data["overlay_path"])

    # RECOMMENDATION
    elements.append(Paragraph("<b>Recommendation</b>", styles["Heading3"]))
    elements.append(Paragraph(
        f"Pesticide: {data['recommendation']['pesticide']}<br/>"
        f"Dosage: {data['recommendation']['dosage']}",
        styles["Normal"]
    ))

    elements.append(Spacer(1, 20))

    elements.append(Paragraph(
        "<i>Report generated by AgriVision WeedSense</i>", styles["Italic"]
    ))

    doc.build(elements)
    buffer.seek(0)
    return buffer